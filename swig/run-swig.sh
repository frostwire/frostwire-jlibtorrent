#!/bin/bash
# WARNING: This script is not meant to be run directly. Every OS script must call it so that env path variables can be set correctly
source build-utils.shinc
abort_if_var_unset "SRC" ${SRC}
abort_if_var_unset "LIBTORRENT_ROOT" ${LIBTORRENT_ROOT}
abort_if_var_unset "BOOST_ROOT" ${BOOST_ROOT}

# Extracted from ../build.gradle
JLIBTORRENT_VERSION=`sed -n -e '/^version /s/.* //p' ../build.gradle | tr -d "'"`
abort_if_var_unset "JLIBTORRENT_VERSION" ${JLIBTORRENT_VERSION}

# SWIG parses a copy of the libtorrent headers it can't read as they are, from an overlay
# directory searched before ${LIBTORRENT_ROOT}/include. The libtorrent checkout itself is never
# modified (frostwire/frostwire-jlibtorrent#339). With SWIG 4.5.1 only torrent_handle.hpp needs it:
# SWIG can't parse the braced default argument `client_data_t userdata = client_data_t{}`.
# Earlier SWIG versions needed seven in-place edits (alert.hpp, file_storage.hpp,
# announce_entry.hpp, ip_filter.hpp); without them 4.5.1 generates byte-identical output.
function prepareHeaderOverlay() {
    HEADER_OVERLAY=$(mktemp -d "${TMPDIR:-/tmp}/jlibtorrent-swig-headers.XXXXXX")
    mkdir -p "${HEADER_OVERLAY}/libtorrent"
    sed 's/userdata = client_data_t{});/userdata);/g' \
        "${LIBTORRENT_ROOT}/include/libtorrent/torrent_handle.hpp" > "${HEADER_OVERLAY}/libtorrent/torrent_handle.hpp"
    if ! grep -q 'client_data_t userdata);' "${HEADER_OVERLAY}/libtorrent/torrent_handle.hpp"; then
        echo "run-swig.sh: torrent_handle.hpp no longer has the client_data_t{} default argument; review prepareHeaderOverlay"
        exit 1
    fi
}

function removeHeaderOverlay() {
    rm -rf "${HEADER_OVERLAY:?}"
}

function runJni()
{
    JAVA_SRC_OUTPUT=../src/main/java/com/frostwire/jlibtorrent/swig
    mkdir -p "${JAVA_SRC_OUTPUT}"
    # Remove what SWIG generated last time, keeping the hand-written files there (OwnedPointer.java).
    grep -l --null 'This file was automatically generated by SWIG' "${JAVA_SRC_OUTPUT:?}"/*.java | xargs -0 rm -f

    if [ -f "libtorrent_jni.cpp" ]; then
        rm libtorrent_jni.cpp
    fi

    # If you're running from Ubuntu and you have swig 3.0.5 you might end up with a segfault running the swig command below
    #./run-swig.sh: line 33: 46204 Segmentation fault
    # Make sure your swig command is compiled from source, version 3.0.12 works on mac
    # https://sourceforge.net/projects/swig/files/swig/swig-3.0.12/swig-3.0.12.tar.gz/download

    swig -c++ -java -o libtorrent_jni.cpp \
        -v \
        -outdir ${JAVA_SRC_OUTPUT} \
        -package com.frostwire.jlibtorrent.swig \
        -I${BOOST_ROOT} \
        -I${HEADER_OVERLAY} \
        -I${LIBTORRENT_ROOT}/include \
        -DBOOST_ASIO_DECL="" \
        -DBOOST_NO_TYPEID=1 \
        -DBOOST_NO_EXCEPTIONS \
        -DBOOST_POSIX_API=1 \
        -DBOOST_SYSTEM_NOEXCEPT="" \
        -DBOOST_SYSTEM_DECL="" \
        -DBOOST_SYSTEM_NO_DEPRECATED=1 \
        -DBOOST_SYSTEM_CONSTEXPR \
        -DBOOST_NO_IOSTREAM \
        -DBOOST_SYMBOL_VISIBLE="" \
        -DBOOST_NOEXCEPT="" \
        -DBOOST_NOEXCEPT_OR_NOTHROW="" \
        -DTORRENT_ABI_VERSION=4 \
        -DTORRENT_VERSION_NAMESPACE_2="" \
        -DTORRENT_VERSION_NAMESPACE_2_END="" \
        -DTORRENT_VERSION_NAMESPACE_3="" \
        -DTORRENT_VERSION_NAMESPACE_3_END="" \
        -DTORRENT_VERSION_NAMESPACE_4="" \
        -DTORRENT_VERSION_NAMESPACE_4_END="" \
        -DTORRENT_IPV6_NAMESPACE="" \
        -DTORRENT_IPV6_NAMESPACE_END="" \
        -DTORRENT_CFG="TORRENT_CFG" \
        -DTORRENT_NO_DEPRECATE \
        -DTORRENT_DEPRECATED_EXPORT="" \
        -DTORRENT_DEPRECATED_MEMBER="" \
        -DTORRENT_DEPRECATED_ENUM="" \
        -DTORRENT_DEPRECATED="" \
        -DTORRENT_EXPORT="" \
        -DTORRENT_UNEXPORT="" \
        -DTORRENT_EXTRA_EXPORT="" \
        -DTORRENT_FORMAT\(x,y\)="" \
        -DNDEBUG=1 \
        -D_bit="" \
        -Dfinal="" \
        libtorrent.i || exit 1

    if [ ! -f "libtorrent_jni.cpp" ]; then
        echo "run-swig.sh: swig failed. exiting."
        exit 1
    fi

    # Resolve the placeholders of includes/libtorrent_ownership.i (frostwire/frostwire-jlibtorrent#337)
    perl resolve-borrow-owner.pl "${JAVA_SRC_OUTPUT}"/*.java || exit 1

    # replace jlibtorrent version
    #uname=`uname -s`
    if [ "$(uname)" == "Darwin" ]; then
      sed -i '' 's/\$JLIBTORRENT_VERSION\$/'"${JLIBTORRENT_VERSION}"'/g' ../src/main/java/com/frostwire/jlibtorrent/swig/libtorrent_jni.java libtorrent_jni.cpp && echo "Updated jlibtorrent version ${JLIBTORRENT_VERSION} in libtorrent_jni.java and libtorrent_jni.cpp"
    else
      sed -i 's/\$JLIBTORRENT_VERSION\$/'"${JLIBTORRENT_VERSION}"'/g' ../src/main/java/com/frostwire/jlibtorrent/swig/libtorrent_jni.java libtorrent_jni.cpp && echo "Updated jlibtorrent version ${JLIBTORRENT_VERSION} in libtorrent_jni.java and libtorrent_jni.cpp"
    fi
}

prepareHeaderOverlay
runJni
removeHeaderOverlay
